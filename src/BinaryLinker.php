<?php

namespace HichemTabTech\Pomposer;

/**
 * Installs package binaries ("bin" in composer.json) into vendor/bin, like Composer:
 * PHP binaries get a proxy that sets $GLOBALS['_composer_autoload_path'] (so tools find
 * vendor/autoload.php even though the package itself lives in the store), other binaries
 * are symlinked. On Windows a .bat proxy is added as well.
 */
class BinaryLinker
{
    public const MARKER = 'Proxy file generated by Pomposer';

    protected string $binDir;

    public function __construct(
        protected string $vendorDir = 'vendor'
    ) {
        $this->vendorDir = rtrim($vendorDir, '/\\');
        $this->binDir = "$this->vendorDir/bin";
    }

    public function link(array $packages): void
    {
        $expected = [];

        foreach ($packages as $package) {
            foreach ((array) ($package['bin'] ?? []) as $bin) {
                $relativeTarget = $package['name'] . '/' . ltrim($bin, '/');
                $target = "$this->vendorDir/$relativeTarget";
                $name = basename($bin);

                if (!is_file($target)) {
                    echo "⚠️  Skipped bin $name for {$package['name']}: $bin not found\n";
                    continue;
                }

                if (isset($expected[$name])) {
                    echo "⚠️  Skipped bin $name for {$package['name']}: name conflicts with {$expected[$name]}\n";
                    continue;
                }

                if (!$this->install($name, $relativeTarget, $target)) {
                    echo "⚠️  Skipped bin $name for {$package['name']}: vendor/bin/$name exists and was not created by Pomposer\n";
                    continue;
                }

                $expected[$name] = $package['name'];
            }
        }

        $this->prune($expected);
    }

    protected function install(string $name, string $relativeTarget, string $target): bool
    {
        $link = "$this->binDir/$name";

        if ((file_exists($link) || is_link($link)) && !$this->isOurs($link)) {
            return false;
        }

        if (!is_dir($this->binDir)) {
            mkdir($this->binDir, 0755, true);
        }

        $this->remove($link);

        // Archives do not keep the executable bit; the target is executed directly when symlinked.
        @chmod($target, 0755);

        if ($this->isPhpFile($target)) {
            file_put_contents($link, $this->phpProxy($relativeTarget));
            chmod($link, 0755);
            $this->writeBatProxy($name, $name, 'php');

            return true;
        }

        if (!@symlink("../$relativeTarget", $link)) {
            file_put_contents($link, $this->shellProxy($relativeTarget));
            chmod($link, 0755);
        }
        $this->writeBatProxy($name, "../$relativeTarget", 'bash');

        return true;
    }

    /**
     * Same detection as Composer: an optional shebang followed by "<?php".
     */
    protected function isPhpFile(string $file): bool
    {
        $head = (string) file_get_contents($file, false, null, 0, 500);

        return preg_match('{^(#!.*\r?\n)?[\r\n\t ]*<\?php}', $head) === 1;
    }

    protected function phpProxy(string $relativeTarget): string
    {
        $marker = self::MARKER;

        return <<<PHP
#!/usr/bin/env php
<?php

/**
 * $marker
 *
 * This file includes the referenced bin path (../$relativeTarget)
 *
 * @generated
 */

namespace Composer;

\$GLOBALS['_composer_bin_dir'] = __DIR__;
\$GLOBALS['_composer_autoload_path'] = __DIR__ . '/../autoload.php';

return include __DIR__ . '/../$relativeTarget';

PHP;
    }

    protected function shellProxy(string $relativeTarget): string
    {
        $marker = self::MARKER;

        return <<<SH
#!/usr/bin/env sh

# $marker

dir=\$(cd "\${0%[/\\\\]*}" > /dev/null && pwd)
export COMPOSER_RUNTIME_BIN_DIR="\$dir"

exec "\$dir/../$relativeTarget" "\$@"

SH;
    }

    protected function writeBatProxy(string $name, string $target, string $runner): void
    {
        if (DIRECTORY_SEPARATOR !== '\\') {
            return;
        }

        $target = str_replace('/', '\\', $target);
        $marker = self::MARKER;

        file_put_contents("$this->binDir/$name.bat", implode("\r\n", [
            '@ECHO OFF',
            "REM $marker",
            'setlocal DISABLEDELAYEDEXPANSION',
            "SET BIN_TARGET=%~dp0\\$target",
            'SET COMPOSER_RUNTIME_BIN_DIR=%~dp0',
            "$runner \"%BIN_TARGET%\" %*",
            '',
        ]));
    }

    /**
     * Ours = a symlink into vendor/ or a file containing our marker.
     */
    protected function isOurs(string $path): bool
    {
        if (is_link($path)) {
            return str_starts_with((string) readlink($path), '../');
        }

        return str_contains((string) file_get_contents($path, false, null, 0, 1024), self::MARKER);
    }

    /**
     * Removes binaries we created that no installed package provides anymore.
     */
    protected function prune(array $expected): void
    {
        if (!is_dir($this->binDir)) {
            return;
        }

        foreach (scandir($this->binDir) as $entry) {
            if ($entry === '.' || $entry === '..') {
                continue;
            }

            $path = "$this->binDir/$entry";
            $name = str_ends_with($entry, '.bat') ? substr($entry, 0, -4) : $entry;

            if (!isset($expected[$name]) && $this->isOurs($path)) {
                $this->remove($path);
            }
        }

        if (count(scandir($this->binDir)) === 2) {
            rmdir($this->binDir);
        }
    }

    protected function remove(string $path): void
    {
        if (is_link($path) || is_file($path)) {
            unlink($path);
        }
    }
}
